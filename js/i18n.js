export let currentLanguage = "en";

export const detectLanguage = (browserLanguage) =>
  typeof browserLanguage === "string" &&
  browserLanguage.toLowerCase().startsWith("it")
    ? "it"
    : "en";

const warnMissingTranslation = (language, key) => {
  console.warn(`Missing translation: ${language}.${key}`);
};

export const t = (key) => {
  const value = translations[currentLanguage]?.[key];

  if (value === undefined) {
    warnMissingTranslation(currentLanguage, key);
    return key;
  }

  return value;
};

export const applyLanguage = (language, root = document) => {
  currentLanguage = translations[language] ? language : "en";
  root.documentElement.lang = currentLanguage;

  const resolveStatic = (key) => {
    const value = translations[currentLanguage][key];

    if (value === undefined) {
      warnMissingTranslation(currentLanguage, key);
    }

    return value;
  };

  root.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = resolveStatic(element.dataset.i18n);
    if (value !== undefined) element.textContent = value;
  });

  root.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = resolveStatic(element.dataset.i18nHtml);
    if (value !== undefined) element.innerHTML = value;
  });

  root
    .querySelectorAll("[data-i18n-attr][data-i18n-key]")
    .forEach((element) => {
      const value = resolveStatic(element.dataset.i18nKey);
      if (value !== undefined) {
        element.setAttribute(element.dataset.i18nAttr, value);
      }
    });

  root.querySelectorAll(".lang-btn").forEach((button) => {
    const isActive = button.dataset.lang === currentLanguage;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  const LanguageChangeEvent = root.defaultView?.CustomEvent;
  if (LanguageChangeEvent) {
    root.dispatchEvent(
      new LanguageChangeEvent("languagechange", {
        detail: { language: currentLanguage },
      }),
    );
  }
};

export const initI18n = (
  root = document,
  browserLanguage = navigator.language,
) => {
  applyLanguage(detectLanguage(browserLanguage), root);

  root.querySelectorAll(".lang-btn").forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.dataset.lang, root);
    });
  });
};
